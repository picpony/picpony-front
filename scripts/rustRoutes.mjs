const MATCHERS = ROUTES.map(([op, method, path]) => ({
  op,
  method,
  pattern: new RegExp(`^${path.replace(/\{[^}]+\}/g, '[^/]+')}$`),
  literal: !path.includes('{'),
}))
  /* A literal path wins over a parameterised one (`/me/favorite-folders/deletions` over `/{id}`). */
  .sort((a, b) => Number(b.literal) - Number(a.literal));

export function opOf(method, url) {
  const path = new URL(url, 'https://fixture.invalid').pathname;
  const verb = String(method || 'GET').toUpperCase();
  return MATCHERS.find((route) => route.method === verb && route.pattern.test(path))?.op ?? null;
}

/** A fixture answer: an object is a 200 JSON body, `null` a 204, `rustError(...)` a refusal. */
export function rustError(status, code, message = code) {
  return { [ERROR]: true, status, body: { error: { code, message } } };
}
const ERROR = Symbol('rust-error');

export function rustResponse(value) {
  if (value === null || value === undefined) return new Response(null, { status: 204 });
  if (value instanceof Response) return value;
  if (value[ERROR]) return Response.json(value.body, { status: value.status });
  return Response.json(value);
}
